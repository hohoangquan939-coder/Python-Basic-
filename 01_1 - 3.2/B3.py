#FOR - IN RANGE

# 0 -> 4
for i in range (5):
    print(i) 

# 6 -> 9
for i in range (6,10):
    print(i)

# 0 -> 9 : step = 2
for i in range (0,10,2):
    print(i)

#While
i=10
while i<100:
    print(i)
    i += 1


